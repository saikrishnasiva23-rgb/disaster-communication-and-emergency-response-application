class EmergencyPublic(ORMModel):
    id: uuid.UUID
    client_emergency_id: str
    emergency_type: str
    emergency_type_label: str | None = None
    description: str | None
    people_count: int
    injured: bool
    trapped: bool
    severity: int | None
    injury_details: str | None
    latitude: float | None
    longitude: float | None
    location_available: bool = False
    occurred_at: datetime
    received_at: datetime
    updated_at: datetime
    priority: PriorityLevel
    priority_score: float
    priority_reason: str | None
    priority_model: str | None
    client_priority: str | None
    status: EmergencyStatus
    status_changed_at: datetime
    status_reason: str | None
    source: EmergencySource
    sync_state: SyncState
    sync_count: int
    first_synced_at: datetime
    last_synced_at: datetime
    origin_client_device_id: str | None
    sender_display_name: str | None
    sender_user_id: uuid.UUID | None
    reporter_user_id: uuid.UUID | None
    relayed_by_client_device_id: str | None
    relayed_by_name: str | None
    hop_count: int
    assigned_team_id: uuid.UUID | None
    cloud_acknowledged_at: datetime | None
    acknowledged_by_user_id: uuid.UUID | None
    local_ble_acknowledged: bool | None
    resolved_at: datetime | None
    resolution_outcome: ResolutionOutcome | None
    resolution_notes: str | None
    distance_km: float | None = Field(default=None, description="Only on nearby queries.")

    @model_validator(mode="after")
    def _derived(self) -> "EmergencyPublic":
        self.location_available = self.latitude is not None and self.longitude is not None
        self.emergency_type_label = emergency_types.info(self.emergency_type).label
        return self


